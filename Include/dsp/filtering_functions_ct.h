/**
 * @defgroup FIR_CT Compile-time specialized FIR filters
 * @ingroup groupFilters
 *
 * The functions of this group compute the same result as
 * arm_fir_<type>(), arm_fir_decimate_<type>() and arm_fir_interpolate_<type>()
 * but the number of taps (and the decimation factor M or the interpolation
 * factor L) are compile-time constants.
 *
 * Each specialized function is generated by a macro:
 *
 * - dsp/filtering_functions_ct.h (this file) provides the macros
 *   declaring the prototypes. It can be included by any user of the functions.
 * - dsp/filtering_functions_ct_impl.h provides the macros generating
 *   the implementations. It must be included by the single C file
 *   in charge of instantiating the functions.
 *
 * The data type is the first argument of the macros. It is the usual
 * CMSIS-DSP suffix : f64, f32, f16, q31, q15 or q7.
 * The number of taps and the factors must be integer literals
 * (or macros expanding to integer literals) because they are used to build
 * the function names.
 *
 * Example :
 * <pre>
 *   // In a header
 *   #include "dsp/filtering_functions_ct.h"
 *   ARM_FIR_CT_DECLARE(f32, 29)                  // arm_fir_n29_f32
 *   ARM_FIR_DECIMATE_CT_DECLARE(q15, 32, 4)      // arm_fir_decimate_n32_m4_q15
 *   ARM_FIR_INTERPOLATE_CT_DECLARE(f32, 48, 3)   // arm_fir_interpolate_n48_l3_f32
 *
 *   // In one C file
 *   #include "dsp/filtering_functions_ct_impl.h"
 *   ARM_FIR_CT_DEFINE(f32, 29)
 *   ARM_FIR_DECIMATE_CT_DEFINE(q15, 32, 4)
 *   ARM_FIR_INTERPOLATE_CT_DEFINE(f32, 48, 3)
 * </pre>
 *
 * The instance structures and the initialization functions are the ones of
 * the generic functions (arm_fir_init_f32(), arm_fir_decimate_init_q15(), ...).
 * The numTaps, M and L fields of the instance are not read : the
 * instance must have been initialized with the same values as the ones used
 * to generate the function.
 *
 * The state buffer must be large enough for the initialization function,
 * which clears it, and for the specialized function. Its size, in samples,
 * is given by ARM_FIR_CT_STATE_SIZE(), ARM_FIR_DECIMATE_CT_STATE_SIZE() and
 * ARM_FIR_INTERPOLATE_CT_STATE_SIZE(), where blockSize is the
 * blockSize given to the initialization function (the maximum number of
 * input samples per call) :
 * - FIR : numTaps + blockSize - 1, plus for the initialization function :
 *   - f32 with Helium : + blockSize
 *   - f16 with Helium : + blockSize rounded up to a multiple of 8
 *   - q31 with Helium : + 2 * (blockSize rounded up to a multiple of 4)
 *   - q15 with ARM_MATH_LOOPUNROLL : + 1
 * - FIR decimator : numTaps + blockSize - 1
 * - FIR interpolator : blockSize + numTaps / L - 1
 *
 * The specialized functions themselves only access the first
 * numTaps + blockSize - 1 samples (blockSize + numTaps / L - 1 for the
 * interpolator).
 *
 * The instance structures do not record the size of the state buffer, so
 * it cannot be checked at run time. When the state buffer is an array, its
 * size can be checked at build time with ARM_FIR_CT_STATE_CHECK(),
 * ARM_FIR_DECIMATE_CT_STATE_CHECK() and ARM_FIR_INTERPOLATE_CT_STATE_CHECK() :
 * <pre>
 *   #define NUMTAPS   29
 *   #define BLOCKSIZE 64
 *   static float32_t state[ARM_FIR_CT_STATE_SIZE(f32, NUMTAPS, BLOCKSIZE)];
 *   ARM_FIR_CT_STATE_CHECK(f32, NUMTAPS, BLOCKSIZE, state);
 * </pre>
 *
 * @par Constraints
 * - FIR decimator : blockSize must be a multiple of M
 * - FIR interpolator : numTaps must be a multiple of L
 * - The specialized Q15 FIR supports an odd numTaps, but arm_fir_init_q15()
 *   rejects it when ARM_MATH_LOOPUNROLL is defined. In that case, as for
 *   arm_fir_q15(), use numTaps + 1 taps with a last coefficient set to zero.
 *
 * @par Implementation
 * The kernels are written once for all the data types. When Neon or Helium
 * is available, the floating point kernels use the generic vector extension
 * of the compiler (vector_size attribute) instead of intrinsics, so the
 * same code is used for Neon, Helium, f64, f32 and f16.
 * The vector kernels require GCC or Clang (armclang) : with other compilers
 * the scalar kernels are used.
 *
 * @par Configuration
 * The following macros can be defined before including
 * dsp/filtering_functions_ct_impl.h :
 * - ARM_CT_DISABLE_VECTOR : use the scalar kernels even when a SIMD unit is
 *   available
 * - ARM_CT_ENABLE_VECTOR : use the vector kernels on any target supporting the
 *   vector_size attribute (error with a compiler other than GCC or Clang)
 * - ARM_CT_VECTOR_EXT : 1 to build the delayed samples with permutations
 *   (default with Neon), 0 to use unaligned vector loads (default otherwise)
 * - ARM_CT_NB_VECTOR_ACC : number of vector accumulators of the vector FIR
 *   (default 4 with Neon, 2 otherwise)
 * - ARM_CT_NB_ACC_<T> : number of accumulators of the scalar kernels for
 *   the type T
 * - ARM_CT_FULL_UNROLL_MAX_TAPS : above this number of taps, the loops on the
 *   taps of the vector kernels are only partially unrolled (default 128)
 * - ARM_MATH_CT_CHECK : enable run-time checks that the instance has been
 *   initialized with the numTaps, M and L of the function and that the
 *   blockSize of the decimator is a multiple of M (disabled by default)
 * - ARM_CT_ASSERT(COND) : handler of the failed checks
 *   (default : assert() of the C library)
 * - ARM_MATH_CT_RESTRICT_COEFFS : the coefficient pointer of the kernels is
 *   restrict qualified : the coefficients must not overlap the output buffer
 *
 * The state pointer of the kernels is always restrict qualified : the state
 * buffer must not overlap the coefficients, the input and the output buffers
 * (the input samples must not be written in the state buffer by the caller).
 * The input and the output may be the same buffer (in-place processing).
 * The prototypes of the functions are the same in all cases.
 *
 * The following macro must be defined before including
 * dsp/filtering_functions_ct.h (and dsp/filtering_functions_ct_impl.h) :
 * - ARM_MATH_CT_STATIC : ARM_FIR_*_CT_DEFINE define static inline functions
 *   and ARM_FIR_*_CT_DECLARE declares static functions. The functions are
 *   then defined in each file calling them, which allows the compiler to
 *   inline them at the call site (for instance with a constant blockSize)
 *   and several files may define the same function. Each file calling the
 *   functions includes dsp/filtering_functions_ct_impl.h and uses
 *   ARM_FIR_*_CT_DEFINE. The code is duplicated in each file and at each
 *   call site where the compiler decides to inline the function.
 *
 * The numTaps, M and L arguments of the macros are always checked at
 * build time.
 */

